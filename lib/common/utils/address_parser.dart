/// 시/도 이름을 정규화 (축약형을 전체 이름으로 변환)
String _normalizeSido(String sido) {
  // 이미 전체 이름인 경우 그대로 반환
  if (sido.contains("특별시") || sido.contains("광역시") || sido.contains("특별자치시") || sido.contains("도")) {
    return sido;
  }
  
  // 축약형을 전체 이름으로 변환
  final normalizedMap = {
    "서울": "서울특별시",
    "부산": "부산광역시",
    "대구": "대구광역시",
    "인천": "인천광역시",
    "광주": "광주광역시",
    "대전": "대전광역시",
    "울산": "울산광역시",
    "세종": "세종특별자치시",
    "경기": "경기도",
    "강원": "강원도",
    "충북": "충청북도",
    "충남": "충청남도",
    "전북": "전라북도",
    "전남": "전라남도",
    "경북": "경상북도",
    "경남": "경상남도",
    "제주": "제주특별자치도",
  };
  
  return normalizedMap[sido] ?? sido;
}

/// 주소 문자열에서 district_code와 region_code를 추출
/// 
/// 주소 형식 예시:
/// - "서울특별시 강서구 공항대로 543"
/// - "부산광역시 해운대구 해운대해변로 264"
/// - "경기도 수원시 영통구 월드컵로 123"
/// - "대전 동구 판교1길 3" (축약형도 지원)
/// 
/// 반환값: Map<String, String?> {"district_code": "16", "region_code": "01"}
Map<String, String?> parseAddressCodes(String address) {
  // 주소를 공백으로 분리
  final parts = address.trim().split(' ');
  if (parts.length < 2) {
    return {"district_code": null, "region_code": null};
  }

  // 시/도 추출 및 정규화 (첫 번째 부분)
  String sido = _normalizeSido(parts[0]);
  if (sido.isEmpty) {
    return {"district_code": null, "region_code": null};
  }

  // 시/군/구 추출 (두 번째 부분)
  String? sigungu = parts.length > 1 ? parts[1] : null;
  if (sigungu == null || sigungu.isEmpty) {
    return {"district_code": null, "region_code": null};
  }

  // 주소 키 생성 (예: "대전광역시 동구")
  String addressKey = "$sido $sigungu";
  
  // district_code 찾기
  String? districtCode = ADDRESS_TO_DISTRICT[addressKey];
  
  // district_code가 없으면 시/도만으로 시도 (예: "경기도 수원시")
  if (districtCode == null && parts.length > 2) {
    String cityKey = "$sido $sigungu";
    districtCode = ADDRESS_TO_DISTRICT[cityKey];
  }

  // region_code 찾기
  String? regionCode = districtCode != null 
      ? DISTRICT_TO_REGION[districtCode] 
      : null;

  return {
    "district_code": districtCode,
    "region_code": regionCode,
  };
}
